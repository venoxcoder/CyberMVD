export function findMethod(id: string): [ArticleItem, MethodItem] | null {
  for (const a of ART) {
    for (const m of a.m) {
      if (m.id === id) return [a, m];
    }
  }
  return null;
}

export function expandSteps(steps: string[]): string[] {
  const out: string[] = [];
  for (const s of steps) {
    if (s.startsWith('@')) {
      const k = s.slice(1).split(' ')[0];
      const rest = s.slice(1 + k.length);
      (B[k] || [s]).forEach((x, i) => out.push(i === 0 && rest ? x + rest : x));
    } else {
      out.push(s);
    }
  }
  return out;
}

export function stepsOfMethod(m: MethodItem): string[][] {
  return m.stages.map((s) => expandSteps(s.s));
}

export function keysOfMethod(m: MethodItem): string[] {
  const keys: string[] = [];
  stepsOfMethod(m).forEach((st, si) => st.forEach((_, i) => keys.push(`${m.id}|${si}|${i}`)));
  return keys;
}
